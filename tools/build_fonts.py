"""Bundle the Patefon web fonts for fully offline use.

Downloads the Latin/Latin-ext/Cyrillic/Cyrillic-ext .woff2 subsets of
Oswald, PT Serif, PT Mono, Inter and JetBrains Mono (all SIL Open Font
License 1.1) and writes:
  rr_archive/web/static/fonts/*.woff2 + fonts.css       (dashboard, /static/fonts/)
  rr_archive/web/static/fonts_embedded.css              (same rules as data: URIs)
  russian_records_archive/_assets/fonts/*.woff2          (copy shipped with the gift)

The gift index.html inlines fonts_embedded.css: browsers refuse to load font
files from file:// pages (CORS), so data: URIs are the only way the type looks
identical when opened offline from a USB stick.

Run once: python tools/build_fonts.py
"""

from __future__ import annotations

import base64
import re
import shutil
import sys
from pathlib import Path

import requests

ROOT = Path(__file__).resolve().parent.parent
STATIC = ROOT / "rr_archive" / "web" / "static"
FONT_DIR = STATIC / "fonts"
GIFT_DIR = ROOT / "russian_records_archive" / "_assets" / "fonts"
# USSR edition: Oswald (constructivist poster headings), PT Serif (stately
# titles, designed for Russian), PT Mono (typewritten telegrams), plus Inter for
# interface text and JetBrains Mono for catalogue numbers.
CSS_URL = ("https://fonts.googleapis.com/css2?family=Oswald:wght@500;600;700"
           "&family=PT+Serif:ital,wght@0,400;0,700;1,400&family=PT+Mono"
           "&family=Inter:wght@400;500;600;700&family=JetBrains+Mono:wght@400;500&display=swap")
SUBSETS = {"latin", "latin-ext", "cyrillic", "cyrillic-ext"}
# A woff2-capable browser UA makes Google serve woff2 with unicode-range subsets.
UA = "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/124.0 Safari/537.36"

BLOCK_RE = re.compile(r"/\*\s*([\w-]+)\s*\*/\s*(@font-face\s*\{[^}]*\})", re.S)
URL_RE = re.compile(r"url\((https://fonts\.gstatic\.com/[^)]+\.woff2)\)")


def slug(family: str, style: str, weight: str, subset: str) -> str:
    return f"{re.sub(r'[^a-z0-9]+', '-', family.lower()).strip('-')}-{weight}{'i' if style == 'italic' else ''}-{subset}"


def main() -> int:
    session = requests.Session()
    session.headers["User-Agent"] = UA
    css = session.get(CSS_URL, timeout=60)
    css.raise_for_status()
    FONT_DIR.mkdir(parents=True, exist_ok=True)
    GIFT_DIR.mkdir(parents=True, exist_ok=True)

    # Group Google's per-weight rules by file: variable fonts (Inter, JetBrains
    # Mono) reuse one file for every weight, so each file gets a single rule with
    # a weight range and is embedded exactly once.
    groups: dict[str, dict] = {}
    for subset, block in BLOCK_RE.findall(css.text):
        if subset not in SUBSETS:
            continue
        remote = URL_RE.search(block).group(1)
        g = groups.setdefault(remote, {
            "family": re.search(r"font-family:\s*'([^']+)'", block).group(1),
            "style": re.search(r"font-style:\s*(\w+)", block).group(1),
            "range": re.search(r"unicode-range:\s*([^;]+);", block).group(1).strip(),
            "subset": subset, "weights": []})
        g["weights"].append(int(re.search(r"font-weight:\s*(\d+)", block).group(1)))

    local_rules, embedded_rules = [], []
    for remote, g in groups.items():
        lo, hi = min(g["weights"]), max(g["weights"])
        name = slug(g["family"], g["style"], str(lo), g["subset"]) + ".woff2"
        data = session.get(remote, timeout=60)
        data.raise_for_status()
        if data.content[:4] != b"wOF2":
            raise SystemExit(f"not a woff2 file: {remote}")
        (FONT_DIR / name).write_bytes(data.content)
        weight = str(lo) if lo == hi else f"{lo} {hi}"

        def rule(src: str) -> str:
            return (f"/* {g['subset']} */\n@font-face {{\n  font-family: '{g['family']}';\n"
                    f"  font-style: {g['style']};\n  font-weight: {weight};\n  font-display: swap;\n"
                    f"  src: url({src}) format('woff2');\n  unicode-range: {g['range']};\n}}")
        local_rules.append(rule(f"/static/fonts/{name}"))
        embedded_rules.append(rule("data:font/woff2;base64," + base64.b64encode(data.content).decode("ascii")))
    fetched = groups

    header = "/* Generated by tools/build_fonts.py - Cormorant Garamond, Inter, JetBrains Mono (SIL OFL 1.1). */\n"
    (FONT_DIR / "fonts.css").write_text(header + "\n".join(local_rules) + "\n", encoding="utf-8")
    (STATIC / "fonts_embedded.css").write_text(header + "\n".join(embedded_rules) + "\n", encoding="utf-8")
    for f in FONT_DIR.glob("*.woff2"):
        shutil.copy2(f, GIFT_DIR / f.name)
    # Embed straight into the gift template, so every exporter (including one
    # already running inside the dashboard) produces offline typography.
    tpl_path = STATIC / "static_catalog.html"
    tpl = tpl_path.read_text(encoding="utf-8")
    begin, end = "/* FONTS:BEGIN */", "/* FONTS:END */"
    a, b = tpl.index(begin) + len(begin), tpl.index(end)
    tpl_path.write_text(tpl[:a] + "\n" + "\n".join(embedded_rules) + "\n" + tpl[b:], encoding="utf-8")
    print(f"template updated: {tpl_path.stat().st_size / 1024:.0f} KB")
    total = sum(f.stat().st_size for f in FONT_DIR.glob("*.woff2"))
    print(f"{len(fetched)} font files ({total / 1024:.0f} KB), {len(local_rules)} @font-face rules")
    print(f"embedded css: {(STATIC / 'fonts_embedded.css').stat().st_size / 1024:.0f} KB")
    return 0


if __name__ == "__main__":
    sys.exit(main())
